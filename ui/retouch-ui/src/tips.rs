/// 随机返回一条技巧（用当前分钟做种子，每分钟换一条）
pub fn random_tip() -> &'static str {
    use std::time::{SystemTime, UNIX_EPOCH};
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    // 每分钟切一条
    let idx = (secs / 60) as usize % TIPS.len();
    TIPS[idx]
}

/// 取一条新的（避免和当前重复）
pub fn next_tip(current: &str) -> &'static str {
    let mut idx = 0;
    // 找当前 tip 的索引，然后取下一条
    for (i, t) in TIPS.iter().enumerate() {
        if *t == current {
            idx = (i + 1) % TIPS.len();
            break;
        }
    }
    // 如果没找到当前 tip（比如被删了），取随机
    if idx == 0 {
        random_tip()
    } else {
        TIPS[idx]
    }
}
